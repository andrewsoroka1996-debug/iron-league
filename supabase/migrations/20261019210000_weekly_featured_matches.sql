-- IRON LEAGUE: manually curated, persistent weekly match highlights.
-- READ THIS FIRST: run this migration in Supabase SQL Editor BEFORE deploying the code.
-- No writes to public.matches or the old public.featured_matches table.

CREATE TABLE IF NOT EXISTS public.weekly_featured_matches (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  season integer NOT NULL CHECK (season BETWEEN 1 AND 4),
  position integer NOT NULL CHECK (position BETWEEN 1 AND 5),
  match_id text NOT NULL,
  display_date date NULL,
  display_time time without time zone NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT weekly_featured_unique_position UNIQUE (season, position),
  CONSTRAINT weekly_featured_unique_match UNIQUE (season, match_id),
  CONSTRAINT weekly_featured_time_requires_date CHECK (
    display_time IS NULL OR display_date IS NOT NULL
  )
);

COMMENT ON TABLE public.weekly_featured_matches IS
  'Five manually curated homepage matches per season. No automatic weekly expiry. Display date/time are optional editorial announcements and never edit public.matches.';

ALTER TABLE public.weekly_featured_matches ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.weekly_featured_matches FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.weekly_featured_matches TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.weekly_featured_matches_id_seq TO service_role;

-- Atomic save: moving a match between slots or replacing an occupied slot
-- cannot leave the weekly list half-updated if a constraint fails.
CREATE OR REPLACE FUNCTION public.set_weekly_featured_match(
  p_season integer,
  p_position integer,
  p_match_id text,
  p_display_date date DEFAULT NULL,
  p_display_time time without time zone DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  saved public.weekly_featured_matches%ROWTYPE;
  source_row public.weekly_featured_matches%ROWTYPE;
  target_row public.weekly_featured_matches%ROWTYPE;
BEGIN
  IF p_season IS NULL OR p_season NOT BETWEEN 1 AND 4 THEN
    RAISE EXCEPTION 'Некоректний сезон';
  END IF;
  IF p_position IS NULL OR p_position NOT BETWEEN 1 AND 5 THEN
    RAISE EXCEPTION 'Позиція має бути 1–5';
  END IF;
  IF p_match_id IS NULL OR length(btrim(p_match_id)) = 0 THEN
    RAISE EXCEPTION 'Матч не вибрано';
  END IF;
  IF p_display_time IS NOT NULL AND p_display_date IS NULL THEN
    RAISE EXCEPTION 'Для зазначення часу спочатку вкажіть дату';
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM public.matches m
    WHERE m.id::text = p_match_id AND m.season = p_season
  ) THEN
    RAISE EXCEPTION 'Матч не знайдено у вибраному сезоні';
  END IF;

  -- Serializes writes to slots within one season.
  PERFORM pg_advisory_xact_lock(73192, p_season);

  SELECT * INTO source_row FROM public.weekly_featured_matches
  WHERE season = p_season AND match_id = p_match_id;
  SELECT * INTO target_row FROM public.weekly_featured_matches
  WHERE season = p_season AND position = p_position;

  DELETE FROM public.weekly_featured_matches
  WHERE season = p_season
    AND (position = p_position OR match_id = p_match_id);

  INSERT INTO public.weekly_featured_matches
    (season, position, match_id, display_date, display_time)
  VALUES
    (p_season, p_position, p_match_id, p_display_date, p_display_time)
  RETURNING * INTO saved;

  -- If a match was moved onto another occupied slot, swap them instead
  -- of losing the previous occupant. Preserve that other match's schedule.
  IF source_row.id IS NOT NULL
     AND source_row.position <> p_position
     AND target_row.id IS NOT NULL
     AND target_row.match_id <> p_match_id THEN
    INSERT INTO public.weekly_featured_matches
      (season, position, match_id, display_date, display_time)
    VALUES
      (p_season, source_row.position, target_row.match_id,
       target_row.display_date, target_row.display_time);
  END IF;

  RETURN to_jsonb(saved);
END;
$$;

REVOKE ALL ON FUNCTION public.set_weekly_featured_match(integer, integer, text, date, time without time zone)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.set_weekly_featured_match(integer, integer, text, date, time without time zone)
  TO service_role;
